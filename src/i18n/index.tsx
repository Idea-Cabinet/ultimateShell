export type TranslationKey = keyof typeof translations["zh-CN"];

interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType | null>(null);

export const I18nProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("ultimateshell_lang") as Lang;
    const validLangs: Lang[] = ["zh-CN", "en-US", "ja-JP", "ko-KR", "de-DE", "ru-RU", "fr-FR"];
    if (saved && validLangs.includes(saved)) return saved;

    if (typeof navigator !== "undefined") {
      const nav = navigator.language.toLowerCase();
      if (nav.startsWith("zh")) return "zh-CN";
      if (nav.startsWith("ja")) return "ja-JP";
      if (nav.startsWith("ko")) return "ko-KR";
      if (nav.startsWith("de")) return "de-DE";
      if (nav.startsWith("ru")) return "ru-RU";
      if (nav.startsWith("fr")) return "fr-FR";
    }
    return "en-US";
  });

  const setLang = (newLang: Lang) => {
    setLangState(newLang);
    localStorage.setItem("ultimateshell_lang", newLang);
  };

  const toggleLang = () => {
    const order: Lang[] = ["zh-CN", "en-US", "ja-JP", "ko-KR", "de-DE", "ru-RU", "fr-FR"];
    const idx = order.indexOf(lang);
    const next = order[(idx + 1) % order.length];
    setLang(next);
  };

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    const dict = (translations[lang] as Record<string, string>) || translations["zh-CN"];
    let text: string = dict[key] || (translations["zh-CN"] as Record<string, string>)[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      });
    }
    return text;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, toggleLang, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextType => {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return ctx;
};
